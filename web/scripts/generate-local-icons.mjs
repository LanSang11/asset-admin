import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { dirname, extname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { getIconData } from '@iconify/utils'

const webRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const repoRoot = resolve(webRoot, '..')
const outputPath = resolve(webRoot, 'src/utils/common/local-icon-data.js')
const iconPattern =
  /['"]((?:ant-design|carbon|clarity|icon-park(?:-outline|-solid|-twotone)?|material-symbols|mdi|mingcute|ph|solar|tabler):[a-z0-9-]+)['"]/gi
const sourceExtensions = new Set(['.js', '.mjs', '.vue', '.py', '.json'])

function walk(root) {
  return readdirSync(root, { withFileTypes: true }).flatMap((entry) => {
    const path = join(root, entry.name)
    return entry.isDirectory() ? walk(path) : [path]
  })
}

const names = new Set(['mdi:shape-outline', 'mdi:account-circle-outline'])
const pickerSource = readFileSync(resolve(webRoot, 'src/assets/js/icons.js'), 'utf8')
for (const [, name] of pickerSource.matchAll(/'([^']+)'/g)) {
  names.add(name.replace(/^mdi-/, 'mdi:'))
}

for (const root of [resolve(webRoot, 'src'), resolve(repoRoot, 'deploy')]) {
  for (const path of walk(root).filter((file) => sourceExtensions.has(extname(file)))) {
    const source = readFileSync(path, 'utf8')
    for (const [, name] of source.matchAll(iconPattern)) names.add(name)
  }
}

const collectionCache = new Map()
function loadCollection(prefix) {
  if (!collectionCache.has(prefix)) {
    const path = resolve(webRoot, `node_modules/@iconify/json/json/${prefix}.json`)
    if (!statSync(path).isFile()) throw new Error(`Icon collection missing: ${prefix}`)
    collectionCache.set(prefix, JSON.parse(readFileSync(path, 'utf8')))
  }
  return collectionCache.get(prefix)
}

const data = {}
for (const fullName of [...names].sort()) {
  const separator = fullName.indexOf(':')
  const prefix = fullName.slice(0, separator)
  const name = fullName.slice(separator + 1)
  const icon = getIconData(loadCollection(prefix), name)
  if (!icon) throw new Error(`Local icon data missing: ${fullName}`)
  data[fullName] = [icon.width || 16, icon.height || 16, icon.body, icon.hidden === true]
}

const output =
  `/* eslint-disable prettier/prettier */\n` +
  `// Generated by web/scripts/generate-local-icons.mjs. Keep runtime icon rendering offline.\n` +
  `const LOCAL_ICON_DATA = Object.freeze(${JSON.stringify(data, null, 2)})\n\n` +
  `const FALLBACK_NAME = 'mdi:shape-outline'\n\n` +
  `export function hasLocalIcon(name) {\n  return Object.prototype.hasOwnProperty.call(LOCAL_ICON_DATA, name)\n}\n\n` +
  `export function resolveLocalIcon(name) {\n` +
  `  const [width, height, body, hidden] = LOCAL_ICON_DATA[hasLocalIcon(name) ? name : FALLBACK_NAME]\n` +
  `  return hidden ? { width, height, body, hidden } : { width, height, body }\n` +
  `}\n`

writeFileSync(outputPath, output, 'utf8')
console.log(`Wrote ${Object.keys(data).length} local icons to ${relative(repoRoot, outputPath)}`)
